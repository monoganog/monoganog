FONTS = {"block": BLOCK, "narrow": NARROW, "heavy": HEAVY}


def font_dims(font):
    g = next(iter(font.values()))
    return len(g[0]), len(g)


def validate():
    for name, font in FONTS.items():
        w, h = font_dims(font)
        for ch, rows in font.items():
            assert len(rows) == h, (name, ch, "height")
            for r in rows:
                assert len(r) == w, (name, ch, r, "width")
    return {n: font_dims(f) for n, f in FONTS.items()}


if __name__ == "__main__":
    print(validate())
